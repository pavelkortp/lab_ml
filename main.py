# Імпортуємо все необхідне
import pandas as pd
from pycaret.classification import *

print("Крок 1: Завантаження даних...")
# Завантажуємо НАШ CSV-ФАЙЛ (той, що лежить у папці)
data = pd.read_csv('heart.csv')
print(f"Дані успішно завантажено, {data.shape[0]} рядків.")

# --------------------------------------------------------------------

print("\nКрок 2: Налаштування експерименту PyCaret...")
# Налаштовуємо середовище. Ми хочемо спрогнозувати стовпець 'HeartDisease'
# PyCaret автоматично визначить типи даних (числові, категоріальні)
s = setup(data, target='HeartDisease', session_id=123)

# --------------------------------------------------------------------

print("\nКрок 3: Порівняння моделей...")
# Це найпотужніша команда:
# PyCaret тренує десятки моделей і сортує їх за найкращою метрикою
best_model = compare_models()

print(f"\nНайкраща модель знайдена: {best_model}")

# --------------------------------------------------------------------

print("\nКрок 4: Тюнінг (оптимізація) найкращої моделі...")
# Беремо найкращу модель і намагаємося зробити її ще трішки кращою
tuned_model = tune_model(best_model)

# --------------------------------------------------------------------

print("\nКрок 5: Фіналізація моделі...")
# Тренуємо модель на 100% даних (включаючи тестовий набір)
final_model = finalize_model(tuned_model)

# --------------------------------------------------------------------

print("\nКрок 6: ЗБЕРЕЖЕННЯ МОДЕЛІ ТА ЕКСПЕРИМЕНТУ...")
# Це те, що вам потрібно для веб-додатку

# 1. Зберігаємо саму модель (конвеєр обробки + алгоритм)
# Цей .pkl файл буде використовувати ваш веб-додаток
model_filename = 'heart_failure_model'
save_model(final_model, model_filename)

# 2. Зберігаємо весь експеримент (всі налаштування)
exp_filename = 'heart_failure_experiment'
save_experiment(exp_filename)

print(f"\nУспіх! Модель збережено як '{model_filename}.pkl'")
print(f"Експеримент збережено як '{exp_filename}.pkl'")